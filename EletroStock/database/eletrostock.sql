DROP SCHEMA IF EXISTS ELETROSTOCK;
CREATE SCHEMA ELETROSTOCK;
USE ELETROSTOCK;

CREATE TABLE CATEGORIA (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255) NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE SECAO_NOMINAL (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(50) NOT NULL,
    UNIDADE_MEDIDA VARCHAR(20) NOT NULL DEFAULT 'mm²',
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UK_SECAO_UNIDADE (NOME, UNIDADE_MEDIDA)
) ENGINE=InnoDB;

CREATE TABLE PRODUTO (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    ID_CATEGORIA INT NOT NULL,
    ID_SECAO_NOMINAL INT NULL,
    QUANTIDADE INT NOT NULL DEFAULT 0,
    PRECO_UNITARIO DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PRODUTO_CATEGORIA 
        FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID),
    CONSTRAINT FK_PRODUTO_SECAO 
        FOREIGN KEY (ID_SECAO_NOMINAL) REFERENCES SECAO_NOMINAL (ID)
) ENGINE=InnoDB;

CREATE TABLE MOVIMENTACAO (
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ID_PRODUTO INT NOT NULL,
    TIPO ENUM('ENTRADA', 'SAIDA') NOT NULL,
    QUANTIDADE INT NOT NULL,
    MOTIVO VARCHAR(255) NOT NULL,
    DATA_HORA DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_MOVIMENTACAO_PRODUTO 
        FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO (ID)
) ENGINE=InnoDB;
